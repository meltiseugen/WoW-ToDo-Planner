-- next quest is on the same map. Imported source records are never modified.
local _,TDP=...
local guides=TDP.CollectionWalkthroughs.toys
local routes=TDP.CollectionQuestRoutes
local sources=TDP.CollectionSourceIndex.quests
local function point(map,x,y) return {mapID=map,x=x/100,y=y/100} end
local function copy(value)
    if type(value)~="table" then return value end
    local result={}
    for k,v in pairs(value) do result[k]=copy(v) end
    return result
end
local function quest(id,name,instructions,options)
    local source=sources[id] or {}
    local q={questID=id,name=name,instructions=instructions,requires=copy(source.sourceQuests or {}),
        requiredCount=source.sqreq,faction=source.faction,npcID=source.qgs and source.qgs[1],
        sourceURL="https://www.wowhead.com/quest="..id,turnInReference=true,objectiveReference=true}
    local coord=source.coords and source.coords[1]
    if coord then q.pickup=point(coord[1],coord[2],coord[3]) end
    for k,v in pairs(options or {}) do q[k]=v end
    return q
end
local function attach(ids,route)
    route.version,route.reviewedAt=1,"2026-11-15"
    routes[route.key]=route
    for _,id in ipairs(ids) do
        local guide=guides[id]
        guide.questRoutes=guide.questRoutes or {}
        guide.questRoutes[#guide.questRoutes+1]=route
        guide.keepReferencePins,guide.separateQuestMap=true,true
    end
end

