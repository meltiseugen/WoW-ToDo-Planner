local function copy(value)
    if type(value)~="table" then return value end
    local result={}
    for key,item in pairs(value) do result[key]=copy(item) end
    return result
end
local function point(map,x,y) return {mapID=map,x=x/100,y=y/100} end
local function attach(id,key,vendor,after)
    local route=copy(routes[key])
    route.key="mop-cosmetic-" .. id
    route.name=guides[id].name .. " - reputation and quest access"
    route.reviewedAt,route.version="2026-11-13",1
    route.completionPin,route.satisfiedPin=copy(vendor),copy(vendor)
    route.completionText="Quest introduction complete - reach Exalted and buy " .. guides[id].name
    route.satisfiedText="Exalted and access ready - buy " .. guides[id].name
    route.after=after
    routes[route.key]=route
    guides[id].questRoutes={route}
    guides[id].questRoutesOptional=true
    guides[id].keepReferencePins=true
end

