"""Compile map destinations from recorded guide and acquisition-source evidence.

Run research_description_locations.py before compiling. This file never scans
prose at runtime. Existing authored pins and character quest routes take priority.
"""
from collections import Counter
import json

from catalog_support import ROOT
from import_collection_sources import REPOSITORY, REVISION, shared_lua_tables
from research_description_locations import CACHE


def main():
    rows = json.loads((CACHE / "description-location-paths.json").read_text(encoding="utf-8"))
    overrides = json.loads((ROOT / "Data/Sources/DescriptionLocationOverrides.json").read_text(encoding="utf-8"))
    index = {kind: {} for kind in ("mounts", "pets", "toys", "cosmetics", "achievements")}
    evidence = []
    for row in rows:
        key = f"{row['type']}:{row['id']}"
        override = overrides.get(key)
        if override and override.get("exclude"): continue
        if row["sourceKind"] in ("Unavailable", "Unverified") and not row.get("conditionalUnlock"): continue
        # Achievement records often use a shared "complete the criteria" guide.
        # Their documented source location still supplies a valid Map action;
        # neither that placeholder nor a localized journal description is a gate.
        paths = [p for p in row["paths"] if p["category"] not in ("Promotions", "InGameShop", "TradingPost")]
        active = [p for p in paths if not p["historical"]]
        paths = active or paths
        coordinates, maps, references = [], [], []
        if override and not override.get("useSourceEvidence"):
            coordinates = [{"mapID": p[0], "x": p[1] / 100, "y": p[2] / 100, "label": p[3]} for p in override.get("waypoints", [])]
            maps = override.get("maps", [])
            references = override.get("references", ["Data/Sources/AcquisitionGuides.json"])
            historical = override.get("historical", False)
        else:
            historical = bool(paths) and not active
            seen = set()
            for path in paths:
                label = path.get("locationType") or ("Original acquisition location" if historical else "Acquisition location")
                for mid, x, y in path["coords"]:
                    if (mid, x, y) not in seen:
                        seen.add((mid, x, y))
                        coordinates.append({"mapID": mid, "x": x / 100, "y": y / 100, "label": label})
                for mid in path["maps"]:
                    if mid > 0 and mid not in maps: maps.append(mid)
                url = f"{REPOSITORY}/blob/{REVISION}/db/Standard/Categories/{path['category']}.lua"
                if url not in references: references.append(url)
        if not coordinates and not maps: continue
        location = {"waypoints": coordinates[:40]} if coordinates else {"areaMaps": maps[:40]}
        if historical: location["historical"] = True
        index[row["type"]][row["id"]] = location
        evidence.append({"type": row["type"], "patch": row["patch"], "id": row["id"], "name": row["name"],
                         "locations": location, "references": references,
                         "missingContexts": row["missingContexts"], "hadUnrestrictedAction": row["hadUnrestrictedAction"]})
    supplemental = ROOT / "Data/Sources/AchievementLocationEvidence.json"
    if supplemental.exists():
        for row in json.loads(supplemental.read_text(encoding="utf-8"))["resolved"]:
            if row["id"] in index["achievements"]: continue
            index["achievements"][row["id"]] = row["locations"]
            evidence.append({**row, "missingContexts": [], "hadUnrestrictedAction": False})
    output = ["-- Generated by tools/build_description_locations.py; source research stays offline.",
              "-- ATT-derived data: MIT; see Data/Sources/ATT-LICENSE.txt.",
              "-- Read-only fallback destinations; authored routes and character quests take priority.",
              "local _, TDP = ...", *shared_lua_tables(index, "TDP.CollectionDescriptionLocations"), ""]
    (ROOT / "Data/Sources/CollectionDescriptionLocations.lua").write_text("\n".join(output), encoding="utf-8")
    (ROOT / "Data/Sources/DescriptionLocations.json").write_text(json.dumps(evidence, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({"locations": dict(Counter(r["type"] for r in evidence)), "total": len(evidence),
                      "withPins": sum(bool(r["locations"].get("waypoints")) for r in evidence)}))


if __name__ == "__main__": main()
