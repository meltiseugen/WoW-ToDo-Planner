"""Compile UI-only exclusions from the cached, pinned acquisition catalog."""
from collections import Counter
from pathlib import Path
import tempfile

from lupa.lua51 import lua_type

from catalog_support import ROOT
from import_collection_sources import CATEGORIES, REPOSITORY, REVISION, load_external


def main():
    cache = Path(tempfile.gettempdir()) / "tdp-collection-source-research/att"
    _, categories = load_external(cache)
    excluded = {kind: set() for kind in ("mounts", "pets", "toys", "cosmetics", "achievements")}

    def walk(node, plunderstorm=False):
        if lua_type(node) != "table":
            return
        event = node["e"]
        plunderstorm = plunderstorm or event == 444 or (
            lua_type(event) == "table" and 444 in event.values()
        )
        if plunderstorm:
            if node["_constructor"] == "Mount" and node["spellID"]:
                excluded["mounts"].add(int(node["spellID"]))
            if node["speciesID"]:
                excluded["pets"].add(int(node["speciesID"]))
            # Keep item IDs in both item-based categories so event rewards stay
            # excluded even when a future catalog classifies them differently.
            if node["itemID"]:
                excluded["toys"].add(int(node["itemID"]))
                excluded["cosmetics"].add(int(node["itemID"]))
            achievement = node["achievementID"]
            if not achievement and node["type"] == "a":
                achievement = node["headerID"]
            if achievement:
                excluded["achievements"].add(int(achievement))
        for _, child in (node["g"] or {}).items():
            walk(child, plunderstorm)

    for category in CATEGORIES:
        walk(categories[category])
    lines = [
        "-- Generated by tools/build_collection_ui_exclusions.py.",
        "-- Plunderstorm (event 444): hide from UI regardless of ownership or event availability.",
        f"-- ATT-derived data: MIT; {REPOSITORY}/tree/{REVISION}",
        "-- Catalog records and saved favorites remain intact.",
        "local _, TDP = ...",
        "TDP.CollectionUIExclusions = {",
    ]
    for kind, ids in excluded.items():
        lines.append(f"    {kind} = {{")
        lines.extend(f"        [{identity}] = true," for identity in sorted(ids))
        lines.append("    },")
    lines.extend(["}", ""])
    (ROOT / "Data/Sources/CollectionUIExclusions.lua").write_text("\n".join(lines), encoding="utf-8")
    print(dict(Counter({kind: len(ids) for kind, ids in excluded.items()})))


if __name__ == "__main__":
    main()
