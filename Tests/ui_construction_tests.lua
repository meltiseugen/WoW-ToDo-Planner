UI_TEST_SNAPSHOTS = {}
local function scenario(name, callback)
    mock.trace = {}
    callback()
    UI_TEST_SNAPSHOTS[name] = mock.trace
    print("PASS: " .. name)
end
local planner = TDP.MainWindow:New()
local home = TDP.HomeWindow:New(TDP)
local explorer = TDP.CollectionExplorerWindow:New(home)
local favorites = TDP.FavoritesWindow:New(home)
home:SetWindows(planner, explorer, favorites)

