end)
scenario("collection explorer construction and rendering", function()
    explorer:Build()
    explorer:Render()
    assert(explorer.previewModel:GetScript("OnMouseDown"))
    assert(explorer.previewAchievementButton:GetScript("OnClick"))
end)
scenario("favorites construction and rendering", function()
    favorites:Build()
    favorites:Render()
    assert(favorites.previewModel:GetScript("OnMouseDown"))
    assert(favorites.previewMapButton:GetScript("OnClick"))
end)
