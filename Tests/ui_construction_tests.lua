scenario("home construction and rendering", function()
    home:Build()
    home:Render()
    assert(home.frame)
end)
scenario("task editor create save and edit", function()
    local editor = TDP.TaskEditWindow:New(planner)
    editor:OpenCreate({ title = "UI refactor test", notes = "Preserve editor behavior", boardKey = "GLOBAL" })
    local frame = editor.frame
    frame:SaveTask()
    local task = TODOPlannerDB.tasks[#TODOPlannerDB.tasks]
    assert(task.title == "UI refactor test" and task.notes == "Preserve editor behavior")
    editor:Open(task)
    frame.titleEdit:SetText("Updated title")
    frame:SaveTask()
    assert(task.title == "Updated title")
end)
scenario("task details open layout and criteria", function()
    local window = TDP.TaskDetailWindow:New(planner)
    window:Open(TODOPlannerDB.tasks[#TODOPlannerDB.tasks])
    local frame = window.frame
    frame:GetScript("OnSizeChanged")(frame)
    frame.currentCriteriaRows = {
        { id = 100, name = "Incomplete criterion", title = "Incomplete criterion", canOpen = true, progress = "1/2", progressValue = 1, progressMax = 2 },
        { id = 101, name = "Completed criterion", title = "Completed criterion", completed = true, canOpen = true },
    }
    frame:UpdateNotesLayout()
    assert(#frame.criteriaRows == 2 and frame.titleText:GetText() == "Updated title")
end)
